/**
 * Acceptance check: workbench-ui.
 *
 * Anchor: THE API RESPONSE, VERBATIM.
 * Every rendered figure is a formatted read of an envelope field through the
 * ONE shared formatter module, so the battery asserts (a) the formatter's
 * exact display contracts on the honesty-critical edges, through the REAL
 * `packages/reader/src/format.ts` (imported, not copied), and (b) value parity:
 * the served viewer fixture's headline equals a fresh engine run of the same
 * book bit-for-bit — the viewer's numbers are real engine output, never
 * hand-authored.
 *
 * Pixel correctness is explicitly NOT gated; interaction
 * flows were verified live in the W2-P6 / W3-P7 sit-downs.
 */
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { loadMarketSnapshot } from "@alm/kernel";
import { createEngine, resolveDefaultContext, type RunRequest, type ScenarioNII } from "@alm/engine";
import { pct, scenarioNetAtHorizon, sig, stat } from "@alm/reader/src/format";
import { buildVanillaPortfolio, vanillaAssumptionSet, vanillaScenarios } from "../../vanilla";
import { ACCEPT_TS } from "./handBooks";
import type { CapabilityCheck, CheckLine } from "./types";

export const workbenchUiCheck: CapabilityCheck = {
  capabilityId: "workbench-ui",
  title: "Workbench UI: one tested formatter, values verbatim from the envelope",
  async run({ repoRoot }) {
    const lines: CheckLine[] = [];

    // (a) Formatter display contracts on the honesty-critical edges.
    const tinySe = stat(1.004e-9);
    const neverZero = tinySe !== "0" && tinySe !== "0.00" && Number(tinySe) > 0;
    const exactZero = stat(0) === "0";
    const pct4 = pct(0.039984, 4) === "3.9984%";
    const sigTiny = sig(-3.203e-4) === "-0.0003203";
    const absent: ScenarioNII = { scenarioId: "S0", byFamily: [], totalNet12: 1, totalNet24: 2 };
    const lookupAbsent = scenarioNetAtHorizon(absent, 36) === undefined;
    const ok = neverZero && exactZero && pct4 && sigTiny && lookupAbsent;
    lines.push({
      id: "formatter-contracts",
      status: ok ? "pass" : "fail",
      detail:
        `real src/format.ts: stat(1.004e-9) = "${tinySe}" (a tiny nonzero SE never renders as ` +
        `zero: ${neverZero}); stat(0) = "0" only for an exact envelope zero: ${exactZero}; ` +
        `pct(0.039984,4) = "3.9984%": ${pct4}; sig(-3.203e-4) round-trips: ${sigTiny}; ` +
        `net-at-horizon on a pre-1.2.0 envelope is undefined, never 0: ${lookupAbsent} ` +
        `(anchor: the one formatter is the only display transform; these are its pinned edges)`,
    });

    // (b) Value parity: the served fixture's headline is real engine output.
    // The fixture was regenerated by apps/viewer/scripts/generateFixture.mts on curve default 2
    // (S0 duration 5.366960016565166 -> 5.3663292287711295, EVE $121,065,587.85 -> $120,866,072.27).
    // The check itself is unchanged.
    const fixturePath = resolve(repoRoot, "apps/viewer/public/vanillaRunResult.json");
    const fixture = JSON.parse(readFileSync(fixturePath, "utf8")) as {
      runResult: { eve: { byScenario: Array<{ scenarioId: string; effectiveDurationEquity?: number; eve: number }> } };
    };
    const fixtureBase = fixture.runResult.eve.byScenario.find((s) => s.scenarioId === "S0");

    const portfolio = buildVanillaPortfolio();
    const market = await loadMarketSnapshot(resolve(repoRoot, "packages/kernel/public/market_public.json"));
    const set = vanillaAssumptionSet();
    const request: RunRequest = {
      runId: "accept-ui-parity",
      portfolioId: portfolio.id,
      marketSnapshot: market,
      scenarios: vanillaScenarios(set.id),
      assumptionSets: [set],
      grid: { horizonMonths: 360, asOf: portfolio.asOf },
      seed: "accept",
      timestamps: { ...ACCEPT_TS },
    };
    const engine = createEngine(resolveDefaultContext());
    engine.loadPortfolio(portfolio);
    const fresh = engine.run(request);
    const freshBase = fresh.eve.byScenario.find((s) => s.scenarioId === "S0")!;
    const durParity = Object.is(fixtureBase?.effectiveDurationEquity, freshBase.effectiveDurationEquity);
    const eveParity = Object.is(fixtureBase?.eve, freshBase.eve);
    lines.push({
      id: "fixture-value-parity",
      status: durParity && eveParity ? "pass" : "fail",
      detail:
        `served vanilla fixture S0: effectiveDurationEquity ${fixtureBase?.effectiveDurationEquity} ` +
        `and EVE $${fixtureBase?.eve?.toFixed(2)} are BIT-IDENTICAL to a fresh engine run of the ` +
        `same book: ${durParity && eveParity} (anchor: the viewer's numbers are real engine ` +
        `output — value parity to the last bit, not a hand-authored fixture)`,
    });

    return {
      lines,
      observedNotImplemented: fresh.notImplemented.map((t) => t.layer),
    };
  },
};
